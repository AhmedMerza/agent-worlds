const { open, sleep, OUT } = require('./rec.cjs')
const fs = require('fs')
;(async () => {
  let { b, p, errs } = await open(3440, 1440, false)
  await p.goto('' + (process.env.MOCK_URL || 'http://127.0.0.1:4322') + '/'); await p.waitForSelector('canvas'); await sleep(1800)
  await p.locator('.chip', { hasText: 'repo-d' }).click(); await sleep(300)
  fs.writeFileSync(OUT + '/ultrawide.png', await p.screenshot()); await b.close()
  ;({ b, p, errs } = await open(400, 860, false))
  await p.goto('' + (process.env.MOCK_URL || 'http://127.0.0.1:4322') + '/'); await p.waitForSelector('.tabs'); await sleep(1500)
  fs.writeFileSync(OUT + '/phone.png', await p.screenshot()); await b.close()
  ;({ b, p, errs } = await open(1440, 900, false))
  await p.goto('' + (process.env.MOCK_URL || 'http://127.0.0.1:4322') + '/'); await p.waitForSelector('canvas'); await sleep(1500)
  await p.locator('body').click({ position: { x: 5, y: 5 } }); await p.keyboard.press('?'); await sleep(500)
  fs.writeFileSync(OUT + '/shortcuts.png', await p.screenshot()); await b.close()
  console.log('errors', JSON.stringify(errs))
})()
